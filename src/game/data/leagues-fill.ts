export function applyLeagueFill(leagueId: string, clubs: Club[]): Club[] {
  const extra = LEAGUE_FILL[leagueId];
  if (!extra) return clubs;
  const seen = new Set(clubs.map((c) => c.id));
  const added = extra
    .filter(([id]) => !seen.has(id))
    .map(([id, name, short, primary, secondary, strength]) => ({
      id,
      name,
      short,
      league: leagueId,
      primary,
      secondary,
      strength,
    }));
  return [...clubs, ...added];
}
