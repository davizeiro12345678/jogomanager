-- Append-only, bounded catalog metrics for future database-growth comparisons.
-- This migration never scans application rows and exposes no client read path.
CREATE SCHEMA IF NOT EXISTS database_growth_private;
REVOKE ALL ON SCHEMA database_growth_private FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA database_growth_private TO service_role;

CREATE TABLE database_growth_private.snapshots (
  snapshot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  captured_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  database_name text NOT NULL,
  database_size_bytes bigint NOT NULL CHECK (database_size_bytes >= 0),
  table_count integer NOT NULL DEFAULT 0 CHECK (table_count >= 0),
  index_count integer NOT NULL DEFAULT 0 CHECK (index_count >= 0)
);

CREATE TABLE database_growth_private.table_metrics (
  snapshot_id bigint NOT NULL REFERENCES database_growth_private.snapshots(snapshot_id),
  schema_name text NOT NULL,
  table_name text NOT NULL,
  relation_kind text NOT NULL CHECK (relation_kind IN ('r', 'p')),
  total_bytes bigint NOT NULL CHECK (total_bytes >= 0),
  table_bytes bigint NOT NULL CHECK (table_bytes >= 0),
  index_bytes bigint NOT NULL CHECK (index_bytes >= 0),
  estimated_live_rows bigint NOT NULL CHECK (estimated_live_rows >= 0),
  estimated_dead_rows bigint NOT NULL CHECK (estimated_dead_rows >= 0),
  modified_since_analyze bigint NOT NULL CHECK (modified_since_analyze >= 0),
  sequential_scans bigint NOT NULL CHECK (sequential_scans >= 0),
  index_scans bigint NOT NULL CHECK (index_scans >= 0),
  last_vacuum timestamptz,
  last_autovacuum timestamptz,
  last_analyze timestamptz,
  last_autoanalyze timestamptz,
  PRIMARY KEY (snapshot_id, schema_name, table_name)
);

CREATE TABLE database_growth_private.index_metrics (
  snapshot_id bigint NOT NULL REFERENCES database_growth_private.snapshots(snapshot_id),
  schema_name text NOT NULL,
  table_name text NOT NULL,
  index_name text NOT NULL,
  index_bytes bigint NOT NULL CHECK (index_bytes >= 0),
  index_scans bigint NOT NULL CHECK (index_scans >= 0),
  tuples_read bigint NOT NULL CHECK (tuples_read >= 0),
  tuples_fetched bigint NOT NULL CHECK (tuples_fetched >= 0),
  is_valid boolean NOT NULL,
  is_ready boolean NOT NULL,
  PRIMARY KEY (snapshot_id, schema_name, table_name, index_name)
);

ALTER TABLE database_growth_private.snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE database_growth_private.table_metrics ENABLE ROW LEVEL SECURITY;
ALTER TABLE database_growth_private.index_metrics ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA database_growth_private FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON database_growth_private.snapshots TO service_role;
GRANT SELECT, INSERT ON database_growth_private.table_metrics TO service_role;
GRANT SELECT, INSERT ON database_growth_private.index_metrics TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA database_growth_private TO service_role;

CREATE INDEX database_growth_snapshots_captured_at_idx
  ON database_growth_private.snapshots (captured_at DESC, snapshot_id DESC);
CREATE INDEX database_growth_table_metrics_size_idx
  ON database_growth_private.table_metrics (snapshot_id, total_bytes DESC, schema_name, table_name);
CREATE INDEX database_growth_index_metrics_size_idx
  ON database_growth_private.index_metrics (snapshot_id, index_bytes DESC, schema_name, table_name, index_name);

-- SECURITY INVOKER is deliberate: service_role is the only role allowed to execute
-- these bridges, and the catalog inspection has no privilege escalation path.
CREATE OR REPLACE FUNCTION public.capture_database_growth_snapshot()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_snapshot_id bigint;
  v_captured_at timestamptz := pg_catalog.clock_timestamp();
  v_database_name pg_catalog.name := pg_catalog.current_database();
  v_database_size_bytes bigint;
  v_table_count integer;
  v_index_count integer;
BEGIN
  IF current_user <> 'service_role' THEN
    RAISE EXCEPTION 'database_growth_service_role_required' USING ERRCODE = '28000';
  END IF;

  v_database_size_bytes := pg_catalog.pg_database_size(v_database_name);

  INSERT INTO database_growth_private.snapshots (
    captured_at,
    database_name,
    database_size_bytes
  )
  VALUES (
    v_captured_at,
    v_database_name,
    v_database_size_bytes
  )
  RETURNING snapshot_id INTO v_snapshot_id;

  -- pg_stat_user_tables supplies estimated row/dead-row counters. This is a
  -- catalog/statistics read, not COUNT(*) over any application table.
  INSERT INTO database_growth_private.table_metrics (
    snapshot_id,
    schema_name,
    table_name,
    relation_kind,
    total_bytes,
    table_bytes,
    index_bytes,
    estimated_live_rows,
    estimated_dead_rows,
    modified_since_analyze,
    sequential_scans,
    index_scans,
    last_vacuum,
    last_autovacuum,
    last_analyze,
    last_autoanalyze
  )
  SELECT
    v_snapshot_id,
    stats.schemaname::text,
    stats.relname::text,
    relation.relkind::text,
    pg_catalog.pg_total_relation_size(stats.relid),
    pg_catalog.pg_table_size(stats.relid),
    pg_catalog.pg_indexes_size(stats.relid),
    greatest(stats.n_live_tup, 0),
    greatest(stats.n_dead_tup, 0),
    greatest(stats.n_mod_since_analyze, 0),
    greatest(stats.seq_scan, 0),
    greatest(stats.idx_scan, 0),
    stats.last_vacuum,
    stats.last_autovacuum,
    stats.last_analyze,
    stats.last_autoanalyze
  FROM pg_catalog.pg_stat_user_tables AS stats
  JOIN pg_catalog.pg_class AS relation ON relation.oid = stats.relid
  WHERE relation.relkind IN ('r', 'p');
  GET DIAGNOSTICS v_table_count = ROW_COUNT;

  INSERT INTO database_growth_private.index_metrics (
    snapshot_id,
    schema_name,
    table_name,
    index_name,
    index_bytes,
    index_scans,
    tuples_read,
    tuples_fetched,
    is_valid,
    is_ready
  )
  SELECT
    v_snapshot_id,
    stats.schemaname::text,
    stats.relname::text,
    stats.indexrelname::text,
    pg_catalog.pg_relation_size(stats.indexrelid),
    greatest(stats.idx_scan, 0),
    greatest(stats.idx_tup_read, 0),
    greatest(stats.idx_tup_fetch, 0),
    index_catalog.indisvalid,
    index_catalog.indisready
  FROM pg_catalog.pg_stat_user_indexes AS stats
  JOIN pg_catalog.pg_index AS index_catalog ON index_catalog.indexrelid = stats.indexrelid;
  GET DIAGNOSTICS v_index_count = ROW_COUNT;

  UPDATE database_growth_private.snapshots
  SET table_count = v_table_count,
      index_count = v_index_count
  WHERE snapshot_id = v_snapshot_id;

  RETURN pg_catalog.jsonb_build_object(
    'snapshotId', v_snapshot_id,
    'capturedAt', v_captured_at,
    'databaseName', v_database_name,
    'databaseSizeBytes', v_database_size_bytes,
    'tableCount', v_table_count,
    'indexCount', v_index_count
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.list_database_growth_snapshots(
  p_limit integer DEFAULT 30,
  p_offset integer DEFAULT 0
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_result jsonb;
BEGIN
  IF current_user <> 'service_role' THEN
    RAISE EXCEPTION 'database_growth_service_role_required' USING ERRCODE = '28000';
  END IF;
  IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 100
     OR p_offset IS NULL OR p_offset NOT BETWEEN 0 AND 100000 THEN
    RAISE EXCEPTION 'database_growth_history_bounds_invalid' USING ERRCODE = '22023';
  END IF;

  SELECT COALESCE(
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'snapshotId', snapshot.snapshot_id,
        'capturedAt', snapshot.captured_at,
        'databaseName', snapshot.database_name,
        'databaseSizeBytes', snapshot.database_size_bytes,
        'tableCount', snapshot.table_count,
        'indexCount', snapshot.index_count
      )
      ORDER BY snapshot.captured_at DESC, snapshot.snapshot_id DESC
    ),
    '[]'::jsonb
  )
  INTO v_result
  FROM (
    SELECT snapshot_id, captured_at, database_name, database_size_bytes, table_count, index_count
    FROM database_growth_private.snapshots
    ORDER BY captured_at DESC, snapshot_id DESC
    LIMIT p_limit OFFSET p_offset
  ) AS snapshot;

  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_database_growth_snapshot(
  p_snapshot_id bigint,
  p_table_limit integer DEFAULT 500,
  p_index_limit integer DEFAULT 1000
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_summary jsonb;
  v_tables jsonb;
  v_indexes jsonb;
  v_table_total bigint;
  v_index_total bigint;
BEGIN
  IF current_user <> 'service_role' THEN
    RAISE EXCEPTION 'database_growth_service_role_required' USING ERRCODE = '28000';
  END IF;
  IF p_snapshot_id IS NULL OR p_snapshot_id < 1
     OR p_table_limit IS NULL OR p_table_limit NOT BETWEEN 1 AND 1000
     OR p_index_limit IS NULL OR p_index_limit NOT BETWEEN 1 AND 5000 THEN
    RAISE EXCEPTION 'database_growth_detail_bounds_invalid' USING ERRCODE = '22023';
  END IF;

  SELECT pg_catalog.jsonb_build_object(
    'snapshotId', snapshot.snapshot_id,
    'capturedAt', snapshot.captured_at,
    'databaseName', snapshot.database_name,
    'databaseSizeBytes', snapshot.database_size_bytes,
    'tableCount', snapshot.table_count,
    'indexCount', snapshot.index_count
  ), snapshot.table_count, snapshot.index_count
  INTO v_summary, v_table_total, v_index_total
  FROM database_growth_private.snapshots AS snapshot
  WHERE snapshot.snapshot_id = p_snapshot_id;

  IF v_summary IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT COALESCE(
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'schemaName', metric.schema_name,
        'tableName', metric.table_name,
        'relationKind', metric.relation_kind,
        'totalBytes', metric.total_bytes,
        'tableBytes', metric.table_bytes,
        'indexBytes', metric.index_bytes,
        'estimatedLiveRows', metric.estimated_live_rows,
        'estimatedDeadRows', metric.estimated_dead_rows,
        'modifiedSinceAnalyze', metric.modified_since_analyze,
        'sequentialScans', metric.sequential_scans,
        'indexScans', metric.index_scans,
        'lastVacuum', metric.last_vacuum,
        'lastAutovacuum', metric.last_autovacuum,
        'lastAnalyze', metric.last_analyze,
        'lastAutoanalyze', metric.last_autoanalyze
      )
      ORDER BY metric.total_bytes DESC, metric.schema_name, metric.table_name
    ),
    '[]'::jsonb
  )
  INTO v_tables
  FROM (
    SELECT *
    FROM database_growth_private.table_metrics
    WHERE snapshot_id = p_snapshot_id
    ORDER BY total_bytes DESC, schema_name, table_name
    LIMIT p_table_limit
  ) AS metric;

  SELECT COALESCE(
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'schemaName', metric.schema_name,
        'tableName', metric.table_name,
        'indexName', metric.index_name,
        'indexBytes', metric.index_bytes,
        'indexScans', metric.index_scans,
        'tuplesRead', metric.tuples_read,
        'tuplesFetched', metric.tuples_fetched,
        'isValid', metric.is_valid,
        'isReady', metric.is_ready
      )
      ORDER BY metric.index_bytes DESC, metric.schema_name, metric.table_name, metric.index_name
    ),
    '[]'::jsonb
  )
  INTO v_indexes
  FROM (
    SELECT *
    FROM database_growth_private.index_metrics
    WHERE snapshot_id = p_snapshot_id
    ORDER BY index_bytes DESC, schema_name, table_name, index_name
    LIMIT p_index_limit
  ) AS metric;

  RETURN pg_catalog.jsonb_build_object(
    'summary', v_summary,
    'tables', v_tables,
    'indexes', v_indexes,
    'tableTotal', v_table_total,
    'indexTotal', v_index_total,
    'tablesTruncated', v_table_total > p_table_limit,
    'indexesTruncated', v_index_total > p_index_limit
  );
END;
$$;

REVOKE ALL ON FUNCTION public.capture_database_growth_snapshot() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.list_database_growth_snapshots(integer, integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.get_database_growth_snapshot(bigint, integer, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.capture_database_growth_snapshot() TO service_role;
GRANT EXECUTE ON FUNCTION public.list_database_growth_snapshots(integer, integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.get_database_growth_snapshot(bigint, integer, integer) TO service_role;
